const pinball=JSON.parse(await readFile(new URL('../docs/pinball-production/ADMISSION.json',import.meta.url),'utf8'));
import {cp,mkdir,rm,writeFile,readFile} from 'node:fs/promises';
import {assertReleasedGames,assertProductionInventory} from './release-policy.mjs';
import {catalog} from '../src/catalog.mjs';
import {renderPage} from '../src/render.mjs';
const root = new URL('../',import.meta.url);
await assertReleasedGames(new URL('public/',root));
const highJump=JSON.parse(await readFile(new URL('../docs/high-jump-main/SOURCE-MANIFEST.json',import.meta.url),'utf8'));
const release=JSON.parse(await readFile(new URL('docs/hurdles-main/SOURCE-MANIFEST.json',root),'utf8'));
const rod=JSON.parse(await readFile(new URL('docs/reaction-rod-main/SOURCE-MANIFEST.json',root),'utf8'));
const studio=JSON.parse(await readFile(new URL('docs/studio-main/SOURCE-MANIFEST.json',root),'utf8'));
const jump=JSON.parse(await readFile(new URL('docs/long-jump-main/SOURCE-MANIFEST.json',root),'utf8'));
const fastHands=JSON.parse(await readFile(new URL('docs/fast-hands-main/SOURCE-MANIFEST.json',root),'utf8'));
const polish=JSON.parse(await readFile(new URL('docs/fast-hands-polish/SOURCE-MANIFEST.json',root),'utf8'));
const gestures=JSON.parse(await readFile(new URL('docs/mobile-gestures/SOURCE-MANIFEST.json',root),'utf8'));
const completedIcons=JSON.parse(await readFile(new URL('docs/app-icons-completion/MANIFEST.json',root),'utf8'));
const courtesy=JSON.parse(await readFile(new URL('docs/main-courtesy-help/MANIFEST.json',root),'utf8'));
const expansion=JSON.parse(await readFile(new URL('docs/main-expansion/ADMISSION.json',root),'utf8'));
const allowedPublicPaths=['games/overtime-pinball/tablet-cue-projection.js',...pinball.addedPublicPaths,...expansion.addedPublicPaths,...completedIcons.addedPublicPaths,...courtesy.addedPublicPaths,...release.allowedPublicPaths,...rod.addedPublicPaths,...studio.addedPublicPaths,...jump.addedPublicPaths,...fastHands.addedPublicPaths,...polish.addedPublicPaths,...gestures.addedPublicPaths,...highJump.addedPublicPaths];
await assertProductionInventory(new URL('public/',root),allowedPublicPaths);
const html=renderPage(catalog);
await writeFile(new URL('public/index.html',root),html);
await rm(new URL('dist/',root),{recursive:true,force:true});
await mkdir(new URL('dist/',root),{recursive:true});
await cp(new URL('public/',root),new URL('dist/',root),{recursive:true});
await assertReleasedGames(new URL('dist/',root));
await assertProductionInventory(new URL('dist/',root),allowedPublicPaths);
console.log('Built static Playformosa to dist/');
